defmodule ExMontyCadServer.Docs.ToolReference do
  @moduledoc """
  The tool reference, rendered from the catalogue the server answers with.

  A model reads `tools/list` and nothing else; a person reads this page. Both are
  the same descriptions, this time as Markdown, because a catalogue written twice
  is a catalogue that disagrees with itself the first time somebody edits one of
  them. `mix ex_monty_cad_server.tools_doc` writes it, and a test fails when the
  committed file and the catalogue have drifted apart.
  """

  alias ExMontyCadServer.Mcp
  alias ExMontyCadServer.Mcp.Tools

  # What each engine is, said once: the reference is where a reader meets
  # `cadmpeg_` and `quiddity_` for the first time.
  @engines %{
    "cadmpeg" =>
      "the file: a SolidWorks, CATIA, Inventor, Creo, NX, Fusion, FreeCAD, Rhino or " <>
        "IGES document read into one format-neutral CAD document, and written back out",
    "quiddity" =>
      "the geometry: feature recognition (bosses, holes, risers, pockets, chamfers), the " <>
        "frames a sensor perceives, and the exact surface underneath a feature",
    "monty_cad" =>
      "the memory: a sensed frame as Monty's own percept, and the labelled graph library " <>
        "a run loads",
    "cluster" =>
      "the plugins other nodes offer: experiments, learning modules and motor policies, " <>
        "whether this node answers the call or that one"
  }

  @doc "The whole page, as Markdown."
  @spec render() :: String.t()
  def render do
    tools = Tools.catalogue()

    [
      header(tools),
      summary(tools),
      by_engine(tools),
      what_the_server_says()
    ]
    |> Enum.join("\n")
  end

  defp header(tools) do
    """
    # The tools

    <!-- Generated by `mix ex_monty_cad_server.tools_doc` from the catalogue the
         server answers `tools/list` with. Do not edit: change the catalogue and
         run the task. -->

    #{length(tools)} tools over #{length(engines(tools))} engines. A model reads them
    from `tools/list` and calls them with `tools/call`; this page is the same
    surface for a person, with the argument schemas spelled out.

    """
  end

  defp summary(tools) do
    rows =
      Enum.map_join(tools, "\n", fn tool ->
        "| `#{tool["name"]}` | #{one_line(tool["title"])} | #{engine_name(tool["name"])} | #{effect(tool)} |"
      end)

    """
    ## What is on offer

    | tool | answers | engine | effect |
    | --- | --- | --- | --- |
    #{rows}

    """
  end

  defp by_engine(tools) do
    tools
    |> engines()
    |> Enum.map_join("\n", fn engine ->
      engine_section(engine, Enum.filter(tools, &(engine_name(&1["name"]) == engine)))
    end)
  end

  defp engine_section(engine, tools) do
    sections = Enum.map_join(tools, "\n", fn tool -> tool_section(tool) end)

    """
    ## #{engine}

    #{sentence_for(engine)}

    #{sections}
    """
  end

  defp tool_section(tool) do
    """
    ### `#{tool["name"]}` — #{one_line(tool["title"])}

    #{tool["description"]}

    #{arguments(tool)}

    #{annotations(tool)}
    """
  end

  defp arguments(%{"inputSchema" => %{"properties" => properties}} = tool)
       when map_size(properties) > 0 do
    required = Map.get(tool["inputSchema"], "required", [])

    rows =
      properties
      |> Enum.sort_by(fn {name, _property} -> {name not in required, name} end)
      |> Enum.map_join("\n", fn {name, property} ->
        "| `#{name}` | #{type(property)} | #{if name in required, do: "yes", else: "no"} | #{one_line(property["description"])} |"
      end)

    """
    | argument | type | required | what it is |
    | --- | --- | --- | --- |
    #{rows}
    """
  end

  defp arguments(_tool), do: "It takes no arguments."

  defp annotations(tool) do
    annotations = tool["annotations"] || %{}

    words =
      [
        annotations["readOnlyHint"] && "read-only: it changes nothing",
        annotations["idempotentHint"] == false &&
          "not idempotent: calling it twice is two effects",
        annotations["destructiveHint"] && "destructive"
      ]
      |> Enum.filter(& &1)

    case words do
      [] -> ""
      words -> "**" <> Enum.join(words, "; ") <> ".**"
    end
  end

  defp what_the_server_says do
    """
    ## What the server says about itself

    Every `initialize` answer carries this text, before a model has asked anything:

    > #{Mcp.instructions() |> one_line()}

    """
  end

  defp engines(tools) do
    tools
    |> Enum.map(&engine_name(&1["name"]))
    |> Enum.uniq()
  end

  defp engine_name(name) do
    case Tools.engine(name) do
      {engine, _module} -> Atom.to_string(engine)
      :none -> "other"
    end
  end

  defp sentence_for(engine) do
    case Map.fetch(@engines, engine) do
      {:ok, sentence} -> "**#{engine}** — #{sentence}."
      :error -> "Tools this server answers itself."
    end
  end

  defp effect(%{"annotations" => %{"readOnlyHint" => true}}), do: "reads"
  defp effect(_tool), do: "writes"

  defp type(%{"type" => "array", "items" => %{"type" => item}}), do: "list of #{item}"
  defp type(%{"type" => type}), do: type
  defp type(_property), do: "any"

  defp one_line(nil), do: ""
  defp one_line(text), do: text |> String.replace(~r/\s+/, " ") |> String.trim()
end
